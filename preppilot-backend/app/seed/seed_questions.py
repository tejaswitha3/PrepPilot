def _question_key(question):
    if not isinstance(question, dict):
        return (
            question.category,
            question.topic,
            question.company,
            question.question_text.strip(),
        )
    return (
        question["category"],
        question["topic"],
        question["company"],
        question["question_text"].strip(),
    )


def seed_questions():
    app = create_app()
    with app.app_context():
        existing_questions = {
            _question_key(question)
            for question in Question.query.with_entities(
                Question.category,
                Question.topic,
                Question.company,
                Question.question_text,
            )
        }
        added_by_topic = Counter()

        for item in QUESTION_DATA:
            key = _question_key(item)
            if key in existing_questions:
                continue

            db.session.add(Question(**item))
            existing_questions.add(key)
            added_by_topic[(item["category"], item["topic"], item["company"])] += 1

        db.session.commit()
        added = sum(added_by_topic.values())
        print(f"Added {added} missing questions; preserved all existing questions.")
        for (category, topic, company), count in sorted(
            added_by_topic.items(),
            key=lambda item: (item[0][0], item[0][1], item[0][2] or ""),
        ):
            suffix = f" ({company} demo)" if company else ""
            print(f"  {category} / {topic}{suffix}: {count}")


if __name__ == "__main__":
    seed_questions()
